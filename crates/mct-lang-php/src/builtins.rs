/// Whether `name` is one of PHP's core functions or call-like keywords.
pub(crate) fn is_core_function(name: &str) -> bool {
    CORE_FUNCTIONS
        .binary_search(&name.to_ascii_lowercase().as_str())
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_is_sorted_and_lowercase() {
        assert!(CORE_FUNCTIONS.windows(2).all(|w| w[0] < w[1]));
        assert!(CORE_FUNCTIONS.iter().all(|f| f
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')));
    }

    #[test]
    fn names_compare_case_insensitively() {
        assert!(is_core_function("StrLen"));
        assert!(!is_core_function("str_contains"));
        assert!(!is_core_function("mb_strlen"));
    }
}
