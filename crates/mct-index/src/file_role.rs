//! What a file is for (issue #634): production code, a test, a fixture a
//! test reads, or generated output. Deterministic, from the path and the
//! file's first lines only.
//!
//! The role feeds resolution: a relation from a production file that names
//! its target by name alone is never resolved into a fixture, since a
//! fixture's `parse` or `User` is sample input, not the code the production
//! file runs. A relation that pins its target (a path, module, qualifier or
//! package) still reaches it.

use crate::dead_code::path_looks_like_test;

/// `files.role`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileRole {
    Production,
    Test,
    Fixture,
    Generated,
}

impl FileRole {
    pub fn as_str(self) -> &'static str {
        match self {
            FileRole::Production => "production",
            FileRole::Test => "test",
            FileRole::Fixture => "fixture",
            FileRole::Generated => "generated",
        }
    }
}

/// Directory names whose files are test input, not code under test.
const FIXTURE_SEGMENTS: &[&str] = &[
    "fixtures",
    "fixture",
    "__fixtures__",
    "testdata",
    "test-data",
    "test_data",
    "corpus",
    "__snapshots__",
];

/// Directory names whose files a tool wrote.
const GENERATED_SEGMENTS: &[&str] = &["generated", "__generated__"];

/// Markers a generator writes near the top of its output: Go's
/// `// Code generated … DO NOT EDIT.`, `@generated` (Facebook tools, Cargo
/// lock files, protoc plugins) and the plain `DO NOT EDIT` most others use.
const GENERATED_MARKERS: &[&str] = &["@generated", "DO NOT EDIT", "Code generated by"];

/// How many leading lines are read for a marker.
const MARKER_LINES: usize = 5;

/// The role of the file at `relative_path` with `contents`. A fixture
/// directory wins over a test one (`tests/fixtures/x.rs` is a fixture), and
/// generated output wins over both.
pub fn file_role(relative_path: &str, contents: &str) -> FileRole {
    if contents
        .lines()
        .take(MARKER_LINES)
        .any(|line| GENERATED_MARKERS.iter().any(|marker| line.contains(marker)))
    {
        return FileRole::Generated;
    }
    path_role(relative_path)
}

/// The role `relative_path` alone gives, without reading the file: no
/// generation marker is seen.
pub fn path_role(relative_path: &str) -> FileRole {
    let directories: Vec<String> = relative_path
        .split('/')
        .rev()
        .skip(1)
        .map(str::to_lowercase)
        .collect();
    let has = |names: &[&str]| directories.iter().any(|d| names.contains(&d.as_str()));
    if has(GENERATED_SEGMENTS) {
        FileRole::Generated
    } else if has(FIXTURE_SEGMENTS) {
        FileRole::Fixture
    } else if path_looks_like_test(relative_path) {
        FileRole::Test
    } else {
        FileRole::Production
    }
}

#[cfg(test)]
mod tests {
    use super::{file_role, path_role, FileRole};

    #[test]
    fn a_path_gives_the_role_and_a_fixture_dir_beats_a_test_dir() {
        assert_eq!(path_role("src/lib.rs"), FileRole::Production);
        assert_eq!(path_role("tests/parse.rs"), FileRole::Test);
        assert_eq!(path_role("src/parser_test.go"), FileRole::Test);
        assert_eq!(path_role("tests/fixtures/broken.rs"), FileRole::Fixture);
        assert_eq!(path_role("pkg/testdata/sample.go"), FileRole::Fixture);
        assert_eq!(path_role("web/__generated__/types.ts"), FileRole::Generated);
        // A file named like a fixture directory is not in one.
        assert_eq!(path_role("src/fixtures.rs"), FileRole::Production);
    }

    #[test]
    fn a_generation_marker_in_the_first_lines_makes_a_file_generated() {
        let go = "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n";
        assert_eq!(file_role("api/user.pb.go", go), FileRole::Generated);
        let late = "a\nb\nc\nd\ne\n// DO NOT EDIT\n";
        assert_eq!(file_role("src/late.rs", late), FileRole::Production);
    }
}
